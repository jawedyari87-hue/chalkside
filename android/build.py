"""Build the Chalkside Android app without Gradle or Android Studio.

    py -3 android/build.py              build android/build/chalkside.apk
    py -3 android/build.py --install    ...and install it on a tablet plugged in over USB

A test build that loads the PC's dev server instead of the live site, with WebView debugging
(add ?mock to the address for the fake tutor, which needs no API key):

    py -3 android/build.py --debug --base http://localhost:8791/ --install
    (then `adb reverse tcp:8791 tcp:8791` so the tablet's localhost reaches the PC)

Needs JDK 17 and the Android SDK with platforms/android-35 and build-tools/35.x. It looks in
C:\\Users\\<you>\\Android\\jdk-17 and ...\\Android\\Sdk unless JAVA_HOME / ANDROID_HOME say otherwise.
The APK is signed with the standard debug key in ~/.android/debug.keystore (made if missing), so
every build can install over the last one.
"""

import argparse
import os
import shutil
import subprocess
import sys
import time
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"
PACKAGE = "io.github.jawedyari87_hue.chalkside"
LIVE_URL = "https://jawedyari87-hue.github.io/chalkside/"
MIN_SDK, TARGET_SDK = 30, 35
VERSION_NAME = "1.0"
WIN = os.name == "nt"


def fail(msg):
    print(f"\nerror: {msg}", file=sys.stderr)
    sys.exit(1)


def find_tools():
    home = Path.home() / "Android"
    jdk = Path(os.environ.get("JAVA_HOME") or home / "jdk-17")
    sdk = Path(os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT") or home / "Sdk")
    exe, bat = (".exe", ".bat") if WIN else ("", "")
    if not (jdk / "bin" / f"javac{exe}").exists():
        fail(f"no JDK at {jdk}. Install JDK 17 there or set JAVA_HOME.")
    android_jar = sdk / "platforms" / f"android-{TARGET_SDK}" / "android.jar"
    if not android_jar.exists():
        fail(f"no {android_jar}. Install platforms/android-{TARGET_SDK} or set ANDROID_HOME.")
    versions = sorted(
        (p for p in (sdk / "build-tools").glob("*") if (p / f"aapt2{exe}").exists()),
        key=lambda p: [int(x) if x.isdigit() else 0 for x in p.name.replace("-", ".").split(".")],
    )
    if not versions:
        fail(f"no build-tools in {sdk / 'build-tools'}.")
    bt = versions[-1]
    return {
        "jdk": jdk,
        "javac": jdk / "bin" / f"javac{exe}",
        "keytool": jdk / "bin" / f"keytool{exe}",
        "android_jar": android_jar,
        # android.jar has no LambdaMetafactory.metafactory, which javac needs for lambdas (d8 rewrites them).
        "lambda_stubs": bt / "core-lambda-stubs.jar",
        "aapt2": bt / f"aapt2{exe}",
        "d8": bt / f"d8{bat}",
        "zipalign": bt / f"zipalign{exe}",
        "apksigner": bt / f"apksigner{bat}",
        "adb": sdk / "platform-tools" / f"adb{exe}",
        "build_tools": bt.name,
    }


def run(tools, *args, quiet=False):
    env = dict(os.environ, JAVA_HOME=str(tools["jdk"]))
    env["PATH"] = str(tools["jdk"] / "bin") + os.pathsep + env.get("PATH", "")
    cmd = [str(a) for a in args]
    r = subprocess.run(cmd, env=env, capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip()
    if r.returncode != 0:
        print(out)
        fail(f"{Path(cmd[0]).name} failed (exit {r.returncode})")
    if out and not quiet:
        print(out)
    return out


def step(msg):
    print(f"- {msg}", flush=True)


def build_info(base, debug):
    pkg_dir = BUILD / "gen" / PACKAGE.replace(".", "/")
    pkg_dir.mkdir(parents=True, exist_ok=True)
    (pkg_dir / "BuildInfo.java").write_text(
        f"""package {PACKAGE};

/** Generated by build.py. */
final class BuildInfo {{
    static final String BASE_URL = "{base}";
    static final String LIVE_URL = "{LIVE_URL}";
    static final boolean DEBUG = {"true" if debug else "false"};
    static final String VERSION_NAME = "{VERSION_NAME}";

    private BuildInfo() {{}}
}}
""",
        encoding="utf-8",
    )


def debug_keystore(tools):
    ks = Path.home() / ".android" / "debug.keystore"
    if not ks.exists():
        step(f"making a debug signing key in {ks}")
        ks.parent.mkdir(parents=True, exist_ok=True)
        run(tools, tools["keytool"], "-genkeypair", "-keystore", ks, "-storepass", "android", "-keypass", "android",
            "-alias", "androiddebugkey", "-keyalg", "RSA", "-keysize", "2048", "-validity", "10000",
            "-dname", "CN=Android Debug,O=Android,C=US", quiet=True)
    return ks


def main():
    ap = argparse.ArgumentParser(description="Build the Chalkside Android app.")
    ap.add_argument("--base", default=LIVE_URL, help="web app address to load (default: the live site)")
    ap.add_argument("--debug", action="store_true", help="debuggable build with WebView debugging (chrome://inspect)")
    ap.add_argument("--install", action="store_true", help="install on the device plugged in over USB")
    ap.add_argument("--launch", action="store_true", help="open the app after installing")
    args = ap.parse_args()
    base = args.base if args.base.endswith("/") or "?" in args.base else args.base + "/"
    if not base.startswith(("https://", "http://localhost", "http://127.0.0.1")):
        fail("--base must be https://, or http://localhost for a dev server")
    if '"' in base or "\\" in base:
        fail("--base can't contain quotes or backslashes")

    tools = find_tools()
    print(f"Building Chalkside {VERSION_NAME} ({'debug, ' if args.debug else ''}loads {base}) with build-tools {tools['build_tools']}")
    if BUILD.exists():
        shutil.rmtree(BUILD)
    (BUILD / "classes").mkdir(parents=True)
    build_info(base, args.debug)

    step("compiling resources (aapt2)")
    run(tools, tools["aapt2"], "compile", "--dir", HERE / "res", "-o", BUILD / "res.zip")
    # Minutes since 2026, so each build is newer than the last.
    version_code = int((time.time() - 1767225600) // 60)
    link = [tools["aapt2"], "link", "-o", BUILD / "res.apk", "-I", tools["android_jar"],
            "--manifest", HERE / "AndroidManifest.xml", "--java", BUILD / "gen",
            "--min-sdk-version", MIN_SDK, "--target-sdk-version", TARGET_SDK,
            "--version-code", version_code, "--version-name", VERSION_NAME, "--auto-add-overlay", BUILD / "res.zip"]
    if args.debug:
        link.append("--debug-mode")
    run(tools, *link)

    step("compiling Java (javac)")
    sources = sorted((HERE / "src").rglob("*.java")) + sorted((BUILD / "gen").rglob("*.java"))
    javac = [tools["javac"], "-encoding", "UTF-8", "-source", "8", "-target", "8",
             "-bootclasspath", f"{tools['android_jar']}{os.pathsep}{tools['lambda_stubs']}",
             "-Xlint:deprecation,unchecked", "-Xlint:-options",
             "-d", BUILD / "classes"]
    if args.debug:
        javac.append("-g")
    run(tools, *javac, *sources)
    with zipfile.ZipFile(BUILD / "classes.jar", "w") as jar:
        for f in sorted((BUILD / "classes").rglob("*.class")):
            jar.write(f, f.relative_to(BUILD / "classes").as_posix())

    step("converting to Android bytecode (d8)")
    (BUILD / "dex").mkdir()
    run(tools, tools["d8"], "--debug" if args.debug else "--release", "--min-api", MIN_SDK,
        "--lib", tools["android_jar"], "--output", BUILD / "dex", BUILD / "classes.jar")

    step("packaging, aligning and signing")
    unaligned = BUILD / "unaligned.apk"
    with zipfile.ZipFile(BUILD / "res.apk") as src, zipfile.ZipFile(unaligned, "w") as dst:
        for info in src.infolist():
            dst.writestr(info, src.read(info.filename))  # keeps resources.arsc uncompressed, as Android needs
        dst.write(BUILD / "dex" / "classes.dex", "classes.dex", compress_type=zipfile.ZIP_DEFLATED)
    aligned = BUILD / "aligned.apk"
    run(tools, tools["zipalign"], "-f", "-p", "4", unaligned, aligned)
    apk = BUILD / "chalkside.apk"
    run(tools, tools["apksigner"], "sign", "--ks", debug_keystore(tools), "--ks-pass", "pass:android",
        "--key-pass", "pass:android", "--ks-key-alias", "androiddebugkey", "--out", apk, aligned)
    run(tools, tools["apksigner"], "verify", "--min-sdk-version", MIN_SDK, apk)
    for f in (unaligned, aligned, BUILD / "res.apk"):
        f.unlink()
    print(f"\nBuilt {apk} ({apk.stat().st_size // 1024} KB, version code {version_code})")

    if args.install or args.launch:
        if not tools["adb"].exists():
            fail("adb not found: install platform-tools.")
        step("installing on the tablet (adb)")
        run(tools, tools["adb"], "install", "-r", apk)
        if args.launch:
            run(tools, tools["adb"], "shell", "am", "start", "-n", f"{PACKAGE}/.MainActivity", quiet=True)
        print("Installed.")


if __name__ == "__main__":
    main()
